// Writes src/neon-art.css: the neon themes' generated backdrops (grain, aurora ribbons, stars, sun, floor grid)
// as data-URI custom properties. Run: node apps/web/tools/gen-neon-art.mjs. Seeded, so the output is stable.
import { writeFileSync } from 'node:fs';
import { aurora, floorGrid, grain, stars, sunSVG } from './neon-textures.mjs';

const out = `/* Generated by tools/gen-neon-art.mjs; do not edit by hand. */
:root {
  --art-grain: ${grain(0.9)};
  --art-aurora: ${aurora(7, ['#2bd9a0', '#5a6bff', '#a35cff'], 390, 640, 150)};
  --art-stars: ${stars(11, 60)};
  --art-sun: ${sunSVG()};
  --art-floor: ${floorGrid()};
}
`;
writeFileSync(new URL('../src/neon-art.css', import.meta.url), out);
